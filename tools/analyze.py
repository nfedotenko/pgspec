#!/usr/bin/env python3
"""pgspec analyzer: profile.json -> generated/specialized.hpp

Two proposers share one spec contract (guard_terms + per-site accessor
expressions) and one codegen path:

- rule: joint-distribution top-k — every value tuple at the hot dispatch
  site whose share >= --min-share (up to --max-specs) becomes a spec with
  all fields pinned to constants. Marginals are not enough: two fields can
  each look bimodal while only two of their four combinations ever
  co-occur, and a guard is a conjunction.
- llm (tools/llm_proposer.py): Claude receives the hot-path source and the
  profile and proposes specs, including partial ones the rule can't (pin
  one field, keep others as identity reads). Its output is validated
  against a token whitelist here, then compiled, bit-exactly
  differential-tested and benchmark-gated by the pipeline — the proposer
  proposes, measurement decides. Any failure falls back to the rule
  proposer.
"""

import argparse
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Site registry: maps a probe site to the C++ it controls.
# In a real system this comes from the probe macros themselves
# (or from C++26 reflection over annotated structs).
ENUM_NAMES = {0: "Limit", 1: "Market", 2: "Ioc", 3: "Fok"}


def _show_f64(v):
    return (f"{struct.unpack('<d', struct.pack('<Q', v))[0]!r} "
            f"(bits 0x{v:016x}ULL)")


SITES = {
    "order.type:enum": dict(
        field="o.type",
        decl="OrderType type",
        fmt=lambda v: f"OrderType::{ENUM_NAMES[v]}",
        show=lambda v: f"OrderType::{ENUM_NAMES.get(v, v)}",
    ),
    "order.lot_size:u32": dict(
        field="o.lot_size",
        decl="uint32_t lot_size",
        fmt=lambda v: f"{v}u",
        show=lambda v: str(v),
    ),
    "order.tick_size:f64": dict(
        field="o.tick_size",
        decl="double tick_size",
        # bit-exact reconstruction of the observed double
        fmt=lambda v: f"std::bit_cast<double>(0x{v:016x}ULL)",
        show=_show_f64,
    ),
}

# The joint probe at the dispatch site, its component order, and the
# accessor-name aliases the LLM proposer uses.
JOINT_SITE = "order.hot:joint"
JOINT_COMPONENTS = ["order.type:enum", "order.lot_size:u32", "order.tick_size:f64"]
ACCESSOR_SITES = {
    "type": "order.type:enum",
    "lot_size": "order.lot_size:u32",
    "tick_size": "order.tick_size:f64",
}

# Token whitelist for proposer-supplied C++ expressions. Anything that does
# not tokenize cleanly against this alternation is rejected before codegen.
ALLOWED_TOKENS = re.compile(r"""
    \s+
  | o\.(?:type|lot_size|tick_size|qty|price_ticks)\b
  | OrderType::(?:Limit|Market|Ioc|Fok)\b
  | std::bit_cast<double>
  | 0[xX][0-9a-fA-F]+(?:ULL|uLL|ull)?
  | \d+\.\d*(?:[eE][+-]?\d+)?
  | \d+(?:ULL|LL|[uU])?
  | true\b | false\b
  | == | != | <= | >= | && | \|\|
  | [-+*/%<>!&|(),]
""", re.VERBOSE)

HEADER_PRE = """#pragma once
// AUTO-GENERATED by tools/analyze.py ({proposer} proposer) — do not edit.
// Source profile: {profile_path}
#include <bit>
#include <cstdint>
#include <tuple>
#include "types.hpp"

#define PGSPEC_ENABLED 1

namespace pgspec {{
"""

HEADER_POST = """
using SpecList = std::tuple<{spec_list}>;

}}  // namespace pgspec
"""

PASSTHROUGH = """#pragma once
// AUTO-GENERATED by tools/analyze.py — no specialization was emitted.
#define PGSPEC_ENABLED 0
"""


def validate_expr(expr):
    """Return an error string if the expression leaves the whitelist."""
    if not isinstance(expr, str) or not expr.strip():
        return "empty expression"
    if len(expr) > 200:
        return "expression too long"
    i = 0
    while i < len(expr):
        m = ALLOWED_TOKENS.match(expr, i)
        if not m:
            return f"disallowed token at {expr[i:i + 20]!r}"
        i = m.end()
    return None


def validate_spec(spec):
    """Normalize a proposer spec dict; raise ValueError if invalid.

    Expected shape: {"comment": str, "guard_terms": [expr, ...],
                     "accessors": {"type"|"lot_size"|"tick_size": expr}}
    """
    terms = spec.get("guard_terms")
    if not isinstance(terms, list) or not 1 <= len(terms) <= 8:
        raise ValueError("guard_terms must be a list of 1..8 expressions")
    for t in terms:
        if (err := validate_expr(t)):
            raise ValueError(f"guard term {t!r}: {err}")
    acc = spec.get("accessors")
    if not isinstance(acc, dict) or set(acc) != set(ACCESSOR_SITES):
        raise ValueError(f"accessors must have exactly keys {set(ACCESSOR_SITES)}")
    for k, e in acc.items():
        if (err := validate_expr(e)):
            raise ValueError(f"accessor {k}: {e!r}: {err}")
    comment = re.sub(r"[^\w .,:%()\[\]=<>/+-]", "", str(spec.get("comment", "")))[:160]
    return {"comment": comment, "guard_terms": terms,
            "accessors": {ACCESSOR_SITES[k]: e for k, e in acc.items()}}


def emit_spec(idx, spec):
    guard_lines, acc_lines = [], []
    for i, term in enumerate(spec["guard_terms"]):
        guard_lines.append(f"        const unsigned g{i} = (unsigned)({term});")
    conj = " & ".join(f"g{i}" for i in range(len(spec["guard_terms"])))
    for site in JOINT_COMPONENTS:
        expr = spec["accessors"][site]
        decl = SITES[site]["decl"]
        # A constant expression folds; an identity read stays runtime.
        kw = "constexpr " if "o." not in expr else ""
        arg = "const Order&" if "o." not in expr else "const Order& o"
        acc_lines.append(f"    {kw}{decl}({arg}) const {{ return {expr}; }}")
    body = "\n".join(guard_lines)
    accessors = "\n".join(acc_lines)
    return f"""
// Spec{idx}: {spec["comment"]}
struct Spec{idx} {{
    static constexpr bool specialized = true;

    // Branchless conjunction: one heavily-biased branch at the call site
    // instead of a short-circuit chain of data-dependent branches.
    [[gnu::always_inline]] static inline bool guard(const Order& o) {{
{body}
        return ({conj}) != 0u;
    }}

{accessors}
}};"""


def decode_joint(profile):
    joint = profile.get(JOINT_SITE)
    if not joint:
        return 0, []
    counts = {tuple(int(x) for x in k.split("|")): int(c) for k, c in joint.items()}
    total = sum(counts.values())
    return total, sorted(counts.items(), key=lambda kv: -kv[1])


def show_tuple(values):
    return "(" + ", ".join(
        SITES[s]["show"](v) for s, v in zip(JOINT_COMPONENTS, values)) + ")"


def profile_report(profile):
    lines = []
    for site, hist in sorted(profile.items()):
        if site == JOINT_SITE or site not in SITES:
            continue
        counts = {int(k): int(c) for k, c in hist.items()}
        total = sum(counts.values())
        lines.append(f"## `{site}`  ({total:,} samples, marginal)")
        for v, c in sorted(counts.items(), key=lambda kv: -kv[1])[:5]:
            lines.append(f"- `{SITES[site]['show'](v)}`: {c:,} ({c / total:.2%})")
        lines.append("")
    total, top = decode_joint(profile)
    if top:
        lines.append(f"## `{JOINT_SITE}`  ({total:,} samples, "
                     f"{len(top)} distinct tuples)")
        for values, c in top[:8]:
            lines.append(f"- `{show_tuple(values)}`: {c:,} ({c / total:.2%})")
        lines.append("")
    return lines


def propose_rule(profile, min_share, max_specs):
    total, top = decode_joint(profile)
    specs, covered, lines = [], 0, []
    for values, c in top[:max_specs]:
        share = c / total if total else 0
        if share < min_share:
            break
        specs.append({
            "comment": f"{show_tuple(values)}, share {share:.2%}",
            "guard_terms": [
                f"{SITES[s]['field']} == {SITES[s]['fmt'](v)}"
                for s, v in zip(JOINT_COMPONENTS, values)],
            "accessors": {s: SITES[s]["fmt"](v)
                          for s, v in zip(JOINT_COMPONENTS, values)},
        })
        covered += c
        lines.append(f"- **Spec{len(specs) - 1}** = `{show_tuple(values)}` ({share:.2%})")
    expected_miss = None
    if specs:
        expected_miss = 1.0 - covered / total
        lines.append(f"\n**Coverage: {covered / total:.2%} of samples hit a "
                     f"spec; the rest take the generic path.**")
    return specs, lines, expected_miss


def propose_llm(profile, args):
    import llm_proposer
    sources = "\n".join(
        f"--- {p} ---\n{(ROOT / p).read_text()}"
        for p in ("src/types.hpp", "src/engine.hpp"))
    raw = llm_proposer.propose(
        sources=sources,
        profile_text="\n".join(profile_report(profile)),
        max_specs=args.max_specs,
        model=args.model,
        mock_response=args.mock_response,
    )
    if args.proposal_out:
        with open(args.proposal_out, "w") as f:
            json.dump(raw, f, indent=2)
        print(f"[analyze] raw proposal saved to {args.proposal_out}")

    proposals = raw.get("specs")
    if not isinstance(proposals, list) or not proposals:
        raise ValueError("proposal has no specs")
    specs, lines = [], []
    for p in proposals[:args.max_specs]:
        spec = validate_spec({
            "comment": f"[llm] {p.get('name', '')}",
            "guard_terms": p.get("guard_terms"),
            "accessors": p.get("accessors"),
        })
        specs.append(spec)
        lines.append(f"- **Spec{len(specs) - 1}** `{p.get('name', '')}`: "
                     f"{p.get('rationale', '')}")
    if raw.get("notes"):
        lines.append(f"\n**Proposer notes:** {raw['notes']}")
    # No expectation: coverage of free-form guards can't be derived from
    # the joint histogram without evaluating C++; the monitor falls back
    # to its built-in default.
    return specs, lines, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("profile", help="profile.json from a -DVALPROF run")
    ap.add_argument("output", help="path for generated specialized.hpp")
    ap.add_argument("--proposer", choices=["rule", "llm"], default="rule")
    ap.add_argument("--model", default=None,
                    help="Claude model id for --proposer llm")
    ap.add_argument("--mock-response", default=None,
                    help="JSON file standing in for the LLM response (testing)")
    ap.add_argument("--proposal-out", default=None,
                    help="where to save the raw LLM proposal")
    ap.add_argument("--min-share", type=float, default=0.10,
                    help="rule proposer: minimum joint-tuple share")
    ap.add_argument("--max-specs", type=int, default=4)
    ap.add_argument("--report", default=None, help="write a markdown report here")
    args = ap.parse_args()
    if args.model is None:
        import llm_proposer
        args.model = llm_proposer.MODEL_DEFAULT

    with open(args.profile) as f:
        profile = json.load(f)

    proposer = args.proposer
    if proposer == "llm":
        try:
            specs, decision_lines, expected_miss = propose_llm(profile, args)
        except Exception as e:  # noqa: BLE001 — any LLM failure degrades to rule
            print(f"[analyze] WARNING: llm proposer failed ({e}); "
                  f"falling back to rule proposer", file=sys.stderr)
            proposer = "rule(fallback)"
            specs, decision_lines, expected_miss = propose_rule(
                profile, args.min_share, args.max_specs)
    else:
        specs, decision_lines, expected_miss = propose_rule(
            profile, args.min_share, args.max_specs)

    if specs:
        header = HEADER_PRE.format(profile_path=args.profile, proposer=proposer)
        header += "\n".join(emit_spec(i, s) for i, s in enumerate(specs))
        if expected_miss is not None:
            header += (f"\n\n// Profiled generic-path share, for the runtime "
                       f"miss-rate monitor.\n"
                       f"inline constexpr double kExpectedMiss = {expected_miss:.6f};\n"
                       f"#define PGSPEC_HAS_EXPECTED_MISS 1")
        header += HEADER_POST.format(
            spec_list=", ".join(f"Spec{i}" for i in range(len(specs))))
    else:
        header = PASSTHROUGH

    with open(args.output, "w") as f:
        f.write(header)
    print(f"[analyze] wrote {args.output} ({len(specs)} spec(s), "
          f"proposer: {proposer})")

    if args.report:
        report = ["# pgspec analysis report", "",
                  f"Profile: `{args.profile}`, proposer: {proposer}, "
                  f"min share: {args.min_share:.0%}, max specs: {args.max_specs}",
                  ""]
        report += profile_report(profile)
        report += decision_lines or ["**No specialization emitted.**"]
        with open(args.report, "w") as f:
            f.write("\n".join(report) + "\n")
        print(f"[analyze] wrote {args.report}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
