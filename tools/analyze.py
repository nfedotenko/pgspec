#!/usr/bin/env python3
"""pgspec analyzer: profile.json -> generated/specialized.hpp

Rule-based proposer for the MVP: a probe site qualifies for specialization
when a single value covers >= --threshold of all samples. Each qualifying
site becomes a compile-time constant inside Spec0; the conjunction of
qualifying sites becomes Spec0::guard().

PROPOSER HOOK: this is the seam where an LLM-based proposer plugs in later.
It would receive the same histograms (plus source context) and propose
structural transforms — SoA splits, flat-map replacements, memoization —
emitted through the same codegen path and gated by the same differential
test. The MVP ships only the rule-based proposer.
"""

import argparse
import json
import struct
import sys

# Site registry: maps a probe site to the C++ it controls.
# In a real system this comes from the probe macros themselves
# (or from C++26 reflection over annotated structs).
ENUM_NAMES = {0: "Limit", 1: "Market", 2: "Ioc", 3: "Fok"}

SITES = {
    "order.type:enum": dict(
        field="o.type",
        accessor="OrderType type(const Order& o) const",
        fallback="return o.type;",
        fmt=lambda v: f"OrderType::{ENUM_NAMES[v]}",
        show=lambda v: f"OrderType::{ENUM_NAMES.get(v, v)}",
    ),
    "order.lot_size:u32": dict(
        field="o.lot_size",
        accessor="uint32_t lot_size(const Order& o) const",
        fallback="return o.lot_size;",
        fmt=lambda v: f"{v}u",
        show=lambda v: str(v),
    ),
    "order.tick_size:f64": dict(
        field="o.tick_size",
        accessor="double tick_size(const Order& o) const",
        fallback="return o.tick_size;",
        # bit-exact reconstruction of the observed double
        fmt=lambda v: f"std::bit_cast<double>(0x{v:016x}ULL)",
        show=lambda v: repr(struct.unpack("<d", struct.pack("<Q", v))[0]),
    ),
}

HEADER_TMPL = """#pragma once
// AUTO-GENERATED by tools/analyze.py — do not edit.
// Source profile: {profile_path}
#include <bit>
#include <cstdint>
#include "types.hpp"

#define PGSPEC_ENABLED 1

namespace pgspec {{

struct Spec0 {{
    static constexpr bool specialized = true;

    // Branchless conjunction: each compare materializes as a flag (cset),
    // combined with bitwise &, so the guard costs ONE conditional branch
    // that is heavily biased on both matching and non-matching workloads —
    // instead of a short-circuit chain of data-dependent branches that
    // mispredict when the live distribution drifts from the profile.
    [[gnu::always_inline]] static inline bool guard(const Order& o) {{
{guard_body}
        return ({guard_conj}) != 0u;
    }}

{accessors}
}};

}}  // namespace pgspec
"""

PASSTHROUGH = """#pragma once
// AUTO-GENERATED by tools/analyze.py — no site met the specialization
// threshold, so no specialization was emitted.
#define PGSPEC_ENABLED 0
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("profile", help="profile.json from a -DVALPROF run")
    ap.add_argument("output", help="path for generated specialized.hpp")
    ap.add_argument("--threshold", type=float, default=0.90)
    ap.add_argument("--report", default=None, help="write a markdown report here")
    args = ap.parse_args()

    with open(args.profile) as f:
        profile = json.load(f)

    decisions = []   # (site, value, share, meta)
    report = ["# pgspec analysis report", "",
              f"Profile: `{args.profile}`, threshold: {args.threshold:.0%}", ""]

    for site, hist in sorted(profile.items()):
        meta = SITES.get(site)
        counts = {int(k): int(c) for k, c in hist.items()}
        total = sum(counts.values())
        if total == 0:
            continue
        top = sorted(counts.items(), key=lambda kv: -kv[1])
        report.append(f"## `{site}`  ({total:,} samples)")
        for v, c in top[:5]:
            shown = meta["show"](v) if meta else str(v)
            report.append(f"- `{shown}`: {c:,} ({c / total:.2%})")
        if meta is None:
            report.append("- **skipped**: site not in registry")
            report.append("")
            continue
        value, count = top[0]
        share = count / total
        if share >= args.threshold:
            decisions.append((site, value, share, meta))
            report.append(f"- **specialize** on `{meta['show'](value)}` "
                          f"(share {share:.2%} >= {args.threshold:.0%})")
        else:
            report.append(f"- keep generic (top share {share:.2%} < {args.threshold:.0%})")
        report.append("")

    if decisions:
        # Most selective condition first (lowest share), purely for
        # readability — with a branchless & conjunction all of them are
        # evaluated anyway.
        decisions.sort(key=lambda d: d[2])
        guard_lines = []
        for i, (site, v, share, m) in enumerate(decisions):
            guard_lines.append(
                f"        const unsigned g{i} = "
                f"(unsigned)({m['field']} == {m['fmt'](v)});  // {site}"
            )
        guard_body = "\n".join(guard_lines)
        guard_conj = " & ".join(f"g{i}" for i in range(len(decisions)))
        guard = " && ".join(
            f"{m['field']} == {m['fmt'](v)}" for (_, v, _, m) in decisions
        )
        acc_lines = []
        for site, meta in SITES.items():
            dec = next((d for d in decisions if d[0] == site), None)
            ret_type, rest = meta["accessor"].split(" ", 1)
            if dec is not None:
                _, v, share, m = dec
                body = f"return {m['fmt'](v)};"
                comment = f"    // {site}: share {share:.2%}\n"
                acc_lines.append(f"{comment}    constexpr {ret_type} {rest} {{ {body} }}")
            else:
                acc_lines.append(f"    // {site}: below threshold, stays runtime\n"
                                 f"    {ret_type} {rest} {{ {meta['fallback']} }}")
        header = HEADER_TMPL.format(
            profile_path=args.profile,
            guard_body=guard_body,
            guard_conj=guard_conj,
            accessors="\n\n".join(acc_lines),
        )
        report.append(f"**Guard:** `{guard}`")
    else:
        header = PASSTHROUGH
        report.append("**No specialization emitted.**")

    with open(args.output, "w") as f:
        f.write(header)
    print(f"[analyze] wrote {args.output} "
          f"({len(decisions)} specialized site(s))")

    if args.report:
        with open(args.report, "w") as f:
            f.write("\n".join(report) + "\n")
        print(f"[analyze] wrote {args.report}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
