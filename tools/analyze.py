#!/usr/bin/env python3
"""pgspec analyzer: profile.json -> generated/specialized.hpp

Joint-distribution proposer: specialization candidates are the top value
TUPLES observed at the hot dispatch site, not per-field marginals — two
fields can each look bimodal while only two of their four combinations
ever co-occur, and a guard is a conjunction, so coverage is a property of
the joint distribution. Every tuple whose share >= --min-share (up to
--max-specs) becomes a SpecN struct with compile-time constants and a
branchless guard; the generated SpecList is tried hottest-first by the
dispatch fold in engine.hpp.

PROPOSER HOOK: this is the seam where an LLM-based proposer plugs in later.
It would receive the same histograms (plus source context) and propose
structural transforms — SoA splits, flat-map replacements, memoization —
emitted through the same codegen path and gated by the same differential
test and accept/reject benchmark gate. This file ships the rule-based
proposer only.
"""

import argparse
import json
import struct
import sys

# Site registry: maps a probe site to the C++ it controls.
# In a real system this comes from the probe macros themselves
# (or from C++26 reflection over annotated structs).
ENUM_NAMES = {0: "Limit", 1: "Market", 2: "Ioc", 3: "Fok"}

SITES = {
    "order.type:enum": dict(
        field="o.type",
        decl="OrderType type",
        fmt=lambda v: f"OrderType::{ENUM_NAMES[v]}",
        show=lambda v: f"OrderType::{ENUM_NAMES.get(v, v)}",
    ),
    "order.lot_size:u32": dict(
        field="o.lot_size",
        decl="uint32_t lot_size",
        fmt=lambda v: f"{v}u",
        show=lambda v: str(v),
    ),
    "order.tick_size:f64": dict(
        field="o.tick_size",
        decl="double tick_size",
        # bit-exact reconstruction of the observed double
        fmt=lambda v: f"std::bit_cast<double>(0x{v:016x}ULL)",
        show=lambda v: repr(struct.unpack("<d", struct.pack("<Q", v))[0]),
    ),
}

# The joint probe at the dispatch site and its component order.
JOINT_SITE = "order.hot:joint"
JOINT_COMPONENTS = ["order.type:enum", "order.lot_size:u32", "order.tick_size:f64"]

HEADER_PRE = """#pragma once
// AUTO-GENERATED by tools/analyze.py — do not edit.
// Source profile: {profile_path}
#include <bit>
#include <cstdint>
#include <tuple>
#include "types.hpp"

#define PGSPEC_ENABLED 1

namespace pgspec {{
"""

HEADER_POST = """
using SpecList = std::tuple<{spec_list}>;

}}  // namespace pgspec
"""

PASSTHROUGH = """#pragma once
// AUTO-GENERATED by tools/analyze.py — no joint tuple met the
// specialization threshold, so no specialization was emitted.
#define PGSPEC_ENABLED 0
"""


def show_tuple(values):
    return "(" + ", ".join(
        SITES[s]["show"](v) for s, v in zip(JOINT_COMPONENTS, values)
    ) + ")"


def emit_spec(idx, values, share):
    guard_lines, acc_lines = [], []
    for i, (site, v) in enumerate(zip(JOINT_COMPONENTS, values)):
        m = SITES[site]
        guard_lines.append(
            f"        const unsigned g{i} = "
            f"(unsigned)({m['field']} == {m['fmt'](v)});  // {site}"
        )
        acc_lines.append(
            f"    constexpr {m['decl']}(const Order&) const "
            f"{{ return {m['fmt'](v)}; }}"
        )
    conj = " & ".join(f"g{i}" for i in range(len(JOINT_COMPONENTS)))
    body = "\n".join(guard_lines)
    accessors = "\n".join(acc_lines)
    return f"""
// Spec{idx}: {show_tuple(values)}, share {share:.2%}
struct Spec{idx} {{
    static constexpr bool specialized = true;

    // Branchless conjunction: one heavily-biased branch at the call site
    // instead of a short-circuit chain of data-dependent branches.
    [[gnu::always_inline]] static inline bool guard(const Order& o) {{
{body}
        return ({conj}) != 0u;
    }}

{accessors}
}};"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("profile", help="profile.json from a -DVALPROF run")
    ap.add_argument("output", help="path for generated specialized.hpp")
    ap.add_argument("--min-share", type=float, default=0.10,
                    help="minimum joint-tuple share to specialize on")
    ap.add_argument("--max-specs", type=int, default=4)
    ap.add_argument("--report", default=None, help="write a markdown report here")
    args = ap.parse_args()

    with open(args.profile) as f:
        profile = json.load(f)

    report = ["# pgspec analysis report", "",
              f"Profile: `{args.profile}`, min share: {args.min_share:.0%}, "
              f"max specs: {args.max_specs}", ""]

    # Marginals: report-only context.
    for site, hist in sorted(profile.items()):
        if site == JOINT_SITE or site not in SITES:
            continue
        counts = {int(k): int(c) for k, c in hist.items()}
        total = sum(counts.values())
        report.append(f"## `{site}`  ({total:,} samples, marginal)")
        for v, c in sorted(counts.items(), key=lambda kv: -kv[1])[:5]:
            report.append(f"- `{SITES[site]['show'](v)}`: {c:,} ({c / total:.2%})")
        report.append("")

    # Joint distribution: the actual decision input.
    joint = profile.get(JOINT_SITE)
    specs = []
    if joint:
        counts = {tuple(int(x) for x in k.split("|")): int(c)
                  for k, c in joint.items()}
        total = sum(counts.values())
        top = sorted(counts.items(), key=lambda kv: -kv[1])
        report.append(f"## `{JOINT_SITE}`  ({total:,} samples, "
                      f"{len(top)} distinct tuples)")
        for values, c in top[:8]:
            report.append(f"- `{show_tuple(values)}`: {c:,} ({c / total:.2%})")
        report.append("")
        covered = 0
        for values, c in top[:args.max_specs]:
            share = c / total
            if share < args.min_share:
                break
            specs.append((values, share))
            covered += c
        for i, (values, share) in enumerate(specs):
            report.append(f"- **Spec{i}** = `{show_tuple(values)}` ({share:.2%})")
        report.append(f"\n**Coverage: {covered / total:.2%} of samples hit a "
                      f"spec; the rest take the generic path.**")
    else:
        report.append(f"## no `{JOINT_SITE}` in profile — nothing to specialize")

    if specs:
        header = HEADER_PRE.format(profile_path=args.profile)
        header += "\n".join(emit_spec(i, v, s) for i, (v, s) in enumerate(specs))
        header += HEADER_POST.format(
            spec_list=", ".join(f"Spec{i}" for i in range(len(specs))))
    else:
        header = PASSTHROUGH

    with open(args.output, "w") as f:
        f.write(header)
    print(f"[analyze] wrote {args.output} ({len(specs)} spec(s))")

    if args.report:
        with open(args.report, "w") as f:
            f.write("\n".join(report) + "\n")
        print(f"[analyze] wrote {args.report}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
